// Writes src/wasm-data.js: the WASI build of stochcraft-cli (base64) and the M/M/1 example, embedded in the function.
// Usage: node scripts/make-wasm-data.mjs path/to/stochcraft-cli.wasm path/to/mm1.bpmn
// The wasm comes from the "CLI on WASI" workflow of helenkwok/StochCraft: gh run download <run id> -R helenkwok/StochCraft -n stochcraft-cli-wasip1
import fs from 'node:fs';
const [wasm, mm1] = process.argv.slice(2);
if (!wasm || !mm1) { console.error('usage: node scripts/make-wasm-data.mjs stochcraft-cli.wasm mm1.bpmn'); process.exit(1); }
fs.writeFileSync(new URL('../src/wasm-data.js', import.meta.url),
  `// Generated by scripts/make-wasm-data.mjs; not committed.\nexport const WASM_BASE64 = "${fs.readFileSync(wasm).toString('base64')}";\nexport const MM1 = ${JSON.stringify(fs.readFileSync(mm1, 'utf8'))};\n`);
console.log('wrote src/wasm-data.js');
